import { chromium, expect } from "@playwright/test";
import { PDFDocument, StandardFonts } from "pdf-lib";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const base = process.env.TEST_URL || "http://127.0.0.1:3000";
await mkdir(".artifacts", { recursive: true });
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
const doc = await PDFDocument.create();
const font = await doc.embedFont(StandardFonts.Helvetica);
doc.addPage().drawText("First page, a real private PDF.", { x: 40, y: 700, size: 14, font });
const pdfBuffer = Buffer.from(await doc.save());
try {
  await page.goto(base, { waitUntil: "networkidle" });
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await context.setOffline(true);
  await page.reload({ waitUntil: "domcontentloaded" });
  await expect(page.locator(".offline-banner")).toBeVisible();
  await expect(page.locator(".tool-card")).toHaveCount(20);
  await page.getByRole("button", { name: "Add Merge PDF to favorites", exact: true }).click();
  await page.getByRole("button", { name: "Open Merge PDF", exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles([{ name: "one.pdf", mimeType: "application/pdf", buffer: pdfBuffer }, { name: "two.pdf", mimeType: "application/pdf", buffer: pdfBuffer }]);
  await page.locator(".process-button").click();
  await expect(page.locator(".result-screen")).toBeVisible({ timeout: 60000 });
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  const jobSynced = page.waitForResponse((response) => response.url().endsWith("/api/workspace") && response.request().method() === "POST" && response.status() === 201, { timeout: 30000 });
  await context.setOffline(false);
  await jobSynced;
  await expect.poll(async () => (await (await page.request.get(`${base}/api/workspace`)).json()).history.length).toBe(1);
  const workspace = await (await page.request.get(`${base}/api/workspace`)).json();
  assert.deepEqual(workspace.workspace.favorites, ["merge"]);
  console.log("PASS first-visit offline shell, offline merging, favorites and history reconnection");
  await page.getByRole("tab", { name: "All tools", exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByRole("tab", { name: "Organize", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.locator(".tool-card")).toHaveCount(6);
  await page.keyboard.press("End");
  await expect(page.locator(".tool-card")).toHaveCount(2);
  await page.keyboard.press("Home");
  await expect(page.locator(".tool-card")).toHaveCount(20);
  console.log("PASS keyboard-operated filter tabs");
  await page.getByRole("button", { name: "Help & feedback", exact: true }).click();
  await page.locator(".info-tabs").getByRole("button", { name: "Send feedback", exact: true }).click();
  await page.getByLabel("Your message", { exact: false }).fill("End-to-end test: the PDF workspace and offline experience are working well.");
  await page.getByLabel("Email", { exact: false }).fill("qa@example.invalid");
  const feedbackResponse = page.waitForResponse((response) => response.url().endsWith("/api/workspace") && response.request().method() === "POST" && response.request().postDataJSON()?.action === "feedback");
  await page.locator(".feedback-form .button").click();
  assert.equal((await feedbackResponse).status(), 201);
  await expect(page.locator(".feedback-success")).toBeVisible();
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  console.log("PASS feedback form and database persistence");
  await page.getByRole("button", { name: "Open workspace menu", exact: true }).click();
  await page.getByRole("button", { name: "Workspace settings", exact: true }).click();
  await page.getByRole("button", { name: "Clear recent history", exact: true }).click();
  await page.getByRole("button", { name: "Yes, clear history", exact: true }).click();
  await expect.poll(async () => (await (await page.request.get(`${base}/api/workspace`)).json()).history.length).toBe(0);
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  await expect(page.locator(".primary-navigation").getByRole("button", { name: /My files/ })).not.toContainText("1");
  console.log("PASS history deletion without removing favorites");
  await page.goto(`${base}/?tool=crop`, { waitUntil: "networkidle" });
  await page.locator('input[type="file"]').setInputFiles({ name: "test.pdf", mimeType: "application/pdf", buffer: pdfBuffer });
  await page.getByLabel("Margin on each edge", { exact: false }).fill("-10");
  await page.locator(".process-button").click();
  await expect(page.locator(".form-error")).toContainText("Choose a margin between");
  await page.getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base, { waitUntil: "networkidle" });
  await expect(page.locator(".mobile-brand")).toBeVisible();
  await page.screenshot({ animations: "disabled", path: ".artifacts/mobile-final.png" });
  await page.getByRole("button", { name: "Open Merge PDF", exact: true }).click();
  await page.screenshot({ animations: "disabled", path: ".artifacts/mobile-dialog-final.png" });
  const modal = await page.getByRole("dialog").boundingBox();
  assert(modal && modal.x >= 0 && modal.width <= 390 && modal.y >= 0 && modal.y + modal.height <= 844, "Mobile dialog fits the screen");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  console.log("PASS validation, mobile dialog sizing, and Escape-to-close");
  assert.deepEqual(errors, []);
  console.log("ALL EDGE-CASE CHECKS PASSED");
} catch (error) {
  console.error(error);
  await page.screenshot({ animations: "disabled", path: ".artifacts/edge-failure.png" });
  process.exitCode = 1;
} finally { await browser.close(); }
